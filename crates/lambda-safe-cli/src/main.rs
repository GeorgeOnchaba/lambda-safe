use clap::{Parser, Subcommand, ValueEnum};
use lambda_safe_compiler::{Compiler, CompilerConfig, SourceFormat};
use lambda_safe_emit::{canonical_bytes, signing_key_from_hex};
use lambda_safe_model::{
    CompilationArtifacts, CompileResult, CompileStatus, HardManifest, LambdaCertificate,
};
use lambda_safe_solver::{
    DecisionProcedure, FiniteModelConfig, FiniteModelSolver, Z3ProcessSolver,
};
use lambda_safe_syntax::deserialize_json_strict;
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::sync::Arc;
use std::time::Duration;

#[derive(Debug, Parser)]
#[command(
    name = "lambda-safe",
    version,
    about = "Compile and verify authority-bounded λ-Safe control-plane contracts"
)]
struct Cli {
    /// Decision procedure used for compile operations.
    #[arg(
        long,
        global = true,
        value_enum,
        default_value = "z3",
        env = "LAMBDA_SAFE_SOLVER"
    )]
    solver: SolverChoice,

    /// Z3 executable path.
    #[arg(long, global = true, default_value = "z3", env = "LAMBDA_SAFE_Z3_PATH")]
    z3_path: PathBuf,

    /// Per-obligation solver deadline in milliseconds.
    #[arg(
        long,
        global = true,
        default_value_t = 5_000,
        env = "LAMBDA_SAFE_TIMEOUT_MS"
    )]
    timeout_ms: u64,

    /// Maximum wall-clock budget for one complete compilation in milliseconds.
    #[arg(
        long,
        global = true,
        default_value_t = 30_000,
        env = "LAMBDA_SAFE_MAX_COMPILE_MS"
    )]
    max_compile_ms: u64,

    /// Maximum input size in bytes.
    #[arg(
        long,
        global = true,
        default_value_t = 1_048_576,
        env = "LAMBDA_SAFE_MAX_SOURCE_BYTES"
    )]
    max_source_bytes: usize,

    /// Maximum solver obligations generated by one compilation.
    #[arg(
        long,
        global = true,
        default_value_t = 2_048,
        env = "LAMBDA_SAFE_MAX_SOLVER_OBLIGATIONS"
    )]
    max_solver_obligations: usize,

    #[command(subcommand)]
    command: Command,
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum SolverChoice {
    Z3,
    Finite,
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum InputFormat {
    Auto,
    Lambda,
    Json,
}

impl From<InputFormat> for SourceFormat {
    fn from(value: InputFormat) -> Self {
        match value {
            InputFormat::Auto => Self::Auto,
            InputFormat::Lambda => Self::Lambda,
            InputFormat::Json => Self::Json,
        }
    }
}

#[derive(Clone, Copy, Debug, ValueEnum)]
enum SchemaKind {
    Contract,
    Manifest,
    Certificate,
    CompileRequest,
    CompileResponse,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Parse, statically check, discharge hard obligations and emit artifacts.
    Compile {
        /// Contract file.
        #[arg(short, long)]
        input: PathBuf,
        /// Input syntax.
        #[arg(long, value_enum, default_value = "auto")]
        format: InputFormat,
        /// Artifact directory. Created only after successful certification.
        #[arg(short, long, default_value = "artifacts")]
        output: PathBuf,
        /// File containing a 64-character hexadecimal Ed25519 secret key.
        #[arg(long, env = "LAMBDA_SAFE_SIGNING_KEY_FILE")]
        signing_key_file: Option<PathBuf>,
    },
    /// Parse and run all static gates without invoking a solver.
    Check {
        /// Contract file.
        #[arg(short, long)]
        input: PathBuf,
        /// Input syntax.
        #[arg(long, value_enum, default_value = "auto")]
        format: InputFormat,
    },
    /// Verify a manifest/certificate pair, including an optional signature.
    Verify {
        /// Hard manifest JSON.
        #[arg(long)]
        manifest: PathBuf,
        /// λ-certificate JSON.
        #[arg(long)]
        certificate: PathBuf,
    },
    /// Print versioned compiler and solver information.
    Info,
    /// Print a bundled JSON Schema.
    Schema {
        /// Schema to print.
        #[arg(value_enum)]
        kind: SchemaKind,
    },
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    match run(cli) {
        Ok(code) => ExitCode::from(code),
        Err(message) => {
            eprintln!("lambda-safe: {message}");
            ExitCode::from(70)
        }
    }
}

fn run(cli: Cli) -> Result<u8, String> {
    if let Command::Schema { kind } = &cli.command {
        println!("{}", schema(*kind));
        return Ok(0);
    }

    let mut config = CompilerConfig {
        max_source_bytes: cli.max_source_bytes,
        max_solver_obligations: cli.max_solver_obligations,
        solver_timeout: Duration::from_millis(cli.timeout_ms),
        max_compile_time: Duration::from_millis(cli.max_compile_ms),
        ..CompilerConfig::default()
    };

    match cli.command {
        Command::Compile {
            input,
            format,
            output,
            signing_key_file,
        } => {
            if output.exists() {
                return Err(format!(
                    "refusing to overwrite existing artifact path {}; choose a new output path",
                    output.display()
                ));
            }
            let solver = create_solver(cli.solver, &cli.z3_path)?;
            if let Some(path) = signing_key_file {
                let encoded = fs::read_to_string(&path).map_err(|error| {
                    format!("cannot read signing key {}: {error}", path.display())
                })?;
                config.signing_key = Some(
                    signing_key_from_hex(encoded.trim())
                        .map_err(|error| format!("invalid signing key: {error}"))?,
                );
            }
            let compiler = Compiler::new(solver, config);
            let source = read_source(&input)?;
            let result = compiler.compile(&source, format.into());
            if let Some(artifacts) = &result.artifacts {
                write_artifact_set(&output, artifacts, &result)?;
            }
            print_json(&result)?;
            Ok(exit_for_status(result.status))
        }
        Command::Check { input, format } => {
            let solver: Arc<dyn DecisionProcedure> = Arc::new(FiniteModelSolver::default());
            let compiler = Compiler::new(solver, config);
            let source = read_source(&input)?;
            let result = compiler.check(&source, format.into());
            print_json(&result)?;
            Ok(if result.valid { 0 } else { 2 })
        }
        Command::Verify {
            manifest,
            certificate,
        } => {
            let solver: Arc<dyn DecisionProcedure> = Arc::new(FiniteModelSolver::default());
            let compiler = Compiler::new(solver, config);
            let manifest: HardManifest = read_json(&manifest)?;
            let certificate: LambdaCertificate = read_json(&certificate)?;
            let result = compiler.verify(&manifest, &certificate);
            print_json(&result)?;
            Ok(if result.valid { 0 } else { 5 })
        }
        Command::Info => {
            let solver = create_solver(cli.solver, &cli.z3_path)?;
            let compiler = Compiler::new(solver, config);
            print_json(&compiler.info())?;
            Ok(0)
        }
        Command::Schema { .. } => unreachable!("schema command returned before solver creation"),
    }
}

fn create_solver(
    choice: SolverChoice,
    z3_path: &Path,
) -> Result<Arc<dyn DecisionProcedure>, String> {
    match choice {
        SolverChoice::Z3 => Z3ProcessSolver::discover(z3_path.to_path_buf())
            .map(|solver| Arc::new(solver) as Arc<dyn DecisionProcedure>)
            .map_err(|error| error.to_string()),
        SolverChoice::Finite => Ok(Arc::new(FiniteModelSolver::new(
            FiniteModelConfig::default(),
        ))),
    }
}

fn read_source(path: &Path) -> Result<String, String> {
    fs::read_to_string(path)
        .map_err(|error| format!("cannot read input {}: {error}", path.display()))
}

fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T, String> {
    let source = read_source(path)?;
    deserialize_json_strict(&source)
        .map_err(|error| format!("invalid JSON in {}: {error}", path.display()))
}

fn write_artifact_set(
    output: &Path,
    artifacts: &CompilationArtifacts,
    result: &CompileResult,
) -> Result<(), String> {
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).map_err(|error| {
        format!(
            "cannot create artifact parent directory {}: {error}",
            parent.display()
        )
    })?;
    let name = output
        .file_name()
        .and_then(|value| value.to_str())
        .ok_or_else(|| "artifact output must end in a UTF-8 directory name".to_owned())?;
    let staging = parent.join(format!(".{name}.lambda-safe-stage-{}", std::process::id()));
    fs::create_dir(&staging).map_err(|error| {
        format!(
            "cannot create artifact staging directory {}: {error}",
            staging.display()
        )
    })?;

    let write_result = write_staged_artifacts(&staging, artifacts, result);
    if let Err(error) = write_result {
        let _ = fs::remove_dir_all(&staging);
        return Err(error);
    }
    if output.exists() {
        let _ = fs::remove_dir_all(&staging);
        return Err(format!(
            "artifact output {} appeared during compilation; refusing to overwrite it",
            output.display()
        ));
    }
    fs::rename(&staging, output).map_err(|error| {
        let _ = fs::remove_dir_all(&staging);
        format!(
            "cannot publish artifact directory {}: {error}",
            output.display()
        )
    })
}

fn write_staged_artifacts(
    staging: &Path,
    artifacts: &CompilationArtifacts,
    result: &CompileResult,
) -> Result<(), String> {
    write_canonical(&staging.join("manifest.json"), &artifacts.manifest)?;
    write_canonical(
        &staging.join("lambda-certificate.json"),
        &artifacts.certificate,
    )?;
    write_pretty(&staging.join("compile-result.json"), result)
}

fn write_canonical<T: Serialize>(path: &Path, value: &T) -> Result<(), String> {
    let mut bytes = canonical_bytes(value).map_err(|error| error.to_string())?;
    bytes.push(b'\n');
    fs::write(path, bytes).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

fn write_pretty<T: Serialize>(path: &Path, value: &T) -> Result<(), String> {
    let mut bytes = serde_json::to_vec_pretty(value).map_err(|error| error.to_string())?;
    bytes.push(b'\n');
    fs::write(path, bytes).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

fn print_json<T: Serialize>(value: &T) -> Result<(), String> {
    let output = serde_json::to_string_pretty(value).map_err(|error| error.to_string())?;
    println!("{output}");
    Ok(())
}

const fn exit_for_status(status: CompileStatus) -> u8 {
    match status {
        CompileStatus::StaticallyCertified => 0,
        CompileStatus::MalformedContract
        | CompileStatus::Unsupported
        | CompileStatus::AuthorityViolation => 2,
        CompileStatus::InvariantViolated | CompileStatus::InfeasibleContext => 3,
        CompileStatus::Indeterminate => 4,
    }
}

const fn schema(kind: SchemaKind) -> &'static str {
    match kind {
        SchemaKind::Contract => include_str!("../../../schemas/contract.schema.json"),
        SchemaKind::Manifest => include_str!("../../../schemas/manifest.schema.json"),
        SchemaKind::Certificate => include_str!("../../../schemas/certificate.schema.json"),
        SchemaKind::CompileRequest => include_str!("../../../schemas/compile-request.schema.json"),
        SchemaKind::CompileResponse => {
            include_str!("../../../schemas/compile-response.schema.json")
        }
    }
}
