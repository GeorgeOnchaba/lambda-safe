use std::time::{Duration, Instant};

/// Runtime limits and optional artifact-signing configuration.
#[derive(Clone)]
pub struct CompilerConfig {
    /// Maximum UTF-8 input bytes.
    pub max_source_bytes: usize,
    /// Deadline for each solver obligation.
    pub solver_timeout: Duration,
    /// Wall-clock budget for one complete compilation, including parsing, checking,
    /// solver obligations and artifact emission. No individual solver call may
    /// consume more than the remaining compilation budget.
    pub max_compile_time: Duration,
    /// Static analysis limits.
    pub checks: CheckConfig,
    /// Maximum number of solver obligations generated by one compilation.
    pub max_solver_obligations: usize,
    /// Optional Ed25519 key. Signatures authenticate the certificate digest and
    /// do not alter its semantic meaning.
    pub signing_key: Option<SigningKey>,
}

impl fmt::Debug for CompilerConfig {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("CompilerConfig")
            .field("max_source_bytes", &self.max_source_bytes)
            .field("solver_timeout", &self.solver_timeout)
            .field("max_compile_time", &self.max_compile_time)
            .field("checks", &self.checks)
            .field("max_solver_obligations", &self.max_solver_obligations)
            .field(
                "signing_key",
                &self.signing_key.as_ref().map(|_| "[REDACTED]"),
            )
            .finish()
    }
}

impl Default for CompilerConfig {
    fn default() -> Self {
        Self {
            max_source_bytes: 1_048_576,
            solver_timeout: Duration::from_secs(5),
            max_compile_time: Duration::from_secs(30),
            checks: CheckConfig::default(),
            max_solver_obligations: 2_048,
            signing_key: None,
        }
    }
}

/// Summary returned by static `check` without solver execution.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckSummary {
    /// Contract id.
    pub contract_id: String,
    /// Hard assumption count.
    pub hard_assumptions: usize,
    /// Hard invariant count.
    pub hard_invariants: usize,
    /// Transition count.
    pub transitions: usize,
    /// Linear token count.
    pub linear_tokens: usize,
    /// Non-hard claim count.
    pub excluded_claims: usize,
}

/// Static-check response.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckResult {
    /// True only when parsing and every static gate succeeded.
    pub valid: bool,
    /// Diagnostics.
    pub diagnostics: Vec<Diagnostic>,
    /// Summary on success.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub summary: Option<CheckSummary>,
}

/// Public implementation metadata.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompilerInfo {
    /// Compiler implementation version.
    pub compiler_version: String,
    /// Supported language version.
    pub language_version: String,
    /// Hard-manifest format version.
    pub manifest_schema_version: String,
    /// λ-certificate format version.
    pub certificate_schema_version: String,
    /// Solver identity.
    pub solver: lambda_safe_model::SolverIdentity,
}

/// Thread-safe compiler facade.
pub struct Compiler {
    solver: Arc<dyn DecisionProcedure>,
    config: CompilerConfig,
}

impl fmt::Debug for Compiler {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("Compiler")
            .field("solver", &self.solver.identity())
            .field("config", &self.config)
            .finish()
    }
}

impl Compiler {
    /// Creates a compiler around a decision procedure.
    #[must_use]
    pub fn new(solver: Arc<dyn DecisionProcedure>, config: CompilerConfig) -> Self {
        Self { solver, config }
    }

    /// Public version and solver metadata.
    #[must_use]
    pub fn info(&self) -> CompilerInfo {
        CompilerInfo {
            compiler_version: COMPILER_VERSION.to_owned(),
            language_version: LANGUAGE_VERSION.to_owned(),
            manifest_schema_version: MANIFEST_SCHEMA_VERSION.to_owned(),
            certificate_schema_version: CERTIFICATE_SCHEMA_VERSION.to_owned(),
            solver: self.solver.identity(),
        }
    }

    /// Parses and statically checks a contract without solver execution or
    /// artifact emission.
    #[must_use]
    pub fn check(&self, source: &str, format: SourceFormat) -> CheckResult {
        if let Some(diagnostic) = self.source_limit_diagnostic(source) {
            return CheckResult {
                valid: false,
                diagnostics: vec![diagnostic],
                summary: None,
            };
        }
        let document = match parse_contract(source, format) {
            Ok(document) => document,
            Err(error) => {
                return CheckResult {
                    valid: false,
                    diagnostics: vec![*error.diagnostic],
                    summary: None,
                };
            }
        };
        match check_contract(&document, &self.config.checks) {
            Ok(checked) => CheckResult {
                valid: true,
                diagnostics: Vec::new(),
                summary: Some(summary(&checked)),
            },
            Err(failure) => CheckResult {
                valid: false,
                diagnostics: failure.diagnostics,
                summary: None,
            },
        }
    }

    /// Runs the complete fail-closed compilation pipeline.
    #[must_use]
    pub fn compile(&self, source: &str, format: SourceFormat) -> CompileResult {
        let started = Instant::now();
        let Some(deadline) = started.checked_add(self.config.max_compile_time) else {
            return CompileResult::failed(
                CompileStatus::Indeterminate,
                vec![Diagnostic::error(
                    codes::RESOURCE_LIMIT,
                    "configured compilation deadline overflowed the platform clock",
                )],
            );
        };
        if let Some(diagnostic) = self.source_limit_diagnostic(source) {
            return CompileResult::failed(CompileStatus::Indeterminate, vec![diagnostic]);
        }
        let document = match parse_contract(source, format) {
            Ok(document) => document,
            Err(error) => {
                return CompileResult::failed(
                    CompileStatus::MalformedContract,
                    vec![*error.diagnostic],
                );
            }
        };
        let checked = match check_contract(&document, &self.config.checks) {
            Ok(checked) => checked,
            Err(failure) => {
                return CompileResult::failed(failure.status, failure.diagnostics);
            }
        };
        if Instant::now() >= deadline {
            return resource_indeterminate(
                &checked,
                format!(
                    "compilation exceeded the configured wall-clock budget of {} ms before solver discharge",
                    duration_ms_u64(self.config.max_compile_time),
                ),
            );
        }
        self.discharge(&checked, deadline)
    }

    /// Verifies a manifest/certificate pair without invoking the SMT solver.
    #[must_use]
    pub fn verify(
        &self,
        manifest: &HardManifest,
        certificate: &LambdaCertificate,
    ) -> CertificateVerification {
        verify_artifacts(manifest, certificate)
    }

    fn discharge(&self, checked: &CheckedContract, deadline: Instant) -> CompileResult {
        let solver_identity = self.solver.identity();
        if solver_identity.name.is_empty()
            || solver_identity.version.is_empty()
            || !matches!(
                solver_identity.theory.as_str(),
                "QF_LIA" | "QF_LIA_FINITE_BOUNDS"
            )
        {
            return CompileResult {
                status: CompileStatus::Indeterminate,
                diagnostics: vec![Diagnostic::error(
                    codes::SOLVER_INDETERMINATE,
                    "decision procedure reported an unsupported or incomplete identity",
                )],
                verification: Vec::new(),
                excluded_claims: checked.excluded_claims.clone(),
                artifacts: None,
            };
        }
        let Some(obligation_count) = solver_obligation_count(checked) else {
            return resource_indeterminate(
                checked,
                "solver obligation count overflowed the platform size type".to_owned(),
            );
        };
        if obligation_count > self.config.max_solver_obligations {
            return resource_indeterminate(
                checked,
                format!(
                    "compilation requires {obligation_count} solver obligations; the configured limit is {}",
                    self.config.max_solver_obligations
                ),
            );
        }
        let symbols = checked.symbols.values().cloned().collect::<Vec<_>>();
        let assumptions = checked
            .assumptions
            .iter()
            .map(|claim| claim.expression.clone())
            .collect::<Vec<_>>();
        let mut records = Vec::new();
        let feasibility = SolverQuery {
            id: "context_feasibility".to_owned(),
            symbols: symbols.clone(),
            assertions: assumptions.clone(),
        };
        match self.solve(&feasibility, deadline) {
            Ok(DecisionResult::Sat(counterexample)) => records.push(VerificationRecord {
                obligation_id: feasibility.id,
                obligation_kind: "context_feasibility".to_owned(),
                outcome: VerificationOutcome::Satisfiable,
                counterexample: Some(counterexample),
            }),
            Ok(DecisionResult::Unsat) => {
                records.push(VerificationRecord {
                    obligation_id: feasibility.id,
                    obligation_kind: "context_feasibility".to_owned(),
                    outcome: VerificationOutcome::Unsatisfiable,
                    counterexample: None,
                });
                return CompileResult {
                    status: CompileStatus::InfeasibleContext,
                    diagnostics: vec![Diagnostic::error(
                        codes::INFEASIBLE_CONTEXT,
                        "hard assumption context Γ is infeasible; certification would be vacuous",
                    )],
                    verification: records,
                    excluded_claims: checked.excluded_claims.clone(),
                    artifacts: None,
                };
            }
            Ok(DecisionResult::Unknown(reason)) => {
                return indeterminate(checked, records, feasibility.id, reason);
            }
            Err(error) => {
                return indeterminate(checked, records, feasibility.id, error.to_string());
            }
        }

        let mut diagnostics = Vec::new();
        let mut violated = false;
        let mut undecided = false;

        for invariant in &checked.invariants {
            let mut assertions = assumptions.clone();
            assertions.push(negate(invariant.expression.clone()));
            let query = SolverQuery {
                id: format!("invariant::{}", invariant.id),
                symbols: symbols.clone(),
                assertions,
            };
            match self.solve(&query, deadline) {
                Ok(DecisionResult::Unsat) => records.push(VerificationRecord {
                    obligation_id: query.id,
                    obligation_kind: "invariant_validity".to_owned(),
                    outcome: VerificationOutcome::Unsatisfiable,
                    counterexample: None,
                }),
                Ok(DecisionResult::Sat(counterexample)) => {
                    violated = true;
                    diagnostics.push(
                        Diagnostic::error(
                            codes::INVARIANT_VIOLATED,
                            format!("hard invariant `{}` has a counterexample", invariant.id),
                        )
                        .for_subject(&invariant.id),
                    );
                    records.push(VerificationRecord {
                        obligation_id: query.id,
                        obligation_kind: "invariant_validity".to_owned(),
                        outcome: VerificationOutcome::Satisfiable,
                        counterexample: Some(counterexample),
                    });
                }
                Ok(DecisionResult::Unknown(reason)) => {
                    undecided = true;
                    diagnostics.push(solver_diagnostic(&query.id, reason));
                    records.push(VerificationRecord {
                        obligation_id: query.id,
                        obligation_kind: "invariant_validity".to_owned(),
                        outcome: VerificationOutcome::Indeterminate,
                        counterexample: None,
                    });
                }
                Err(error) => {
                    undecided = true;
                    diagnostics.push(solver_diagnostic(&query.id, error.to_string()));
                    records.push(VerificationRecord {
                        obligation_id: query.id,
                        obligation_kind: "invariant_validity".to_owned(),
                        outcome: VerificationOutcome::Indeterminate,
                        counterexample: None,
                    });
                }
            }
        }

        for transition in &checked.transitions {
            for branch in &transition.branches {
                let preserved = transition
                    .preserves
                    .iter()
                    .filter_map(|id| checked.invariants.iter().find(|claim| &claim.id == id))
                    .collect::<Vec<_>>();

                let mut branch_context = assumptions.clone();
                branch_context.extend(preserved.iter().map(|claim| claim.expression.clone()));
                branch_context.push(branch.relation.clone());
                let feasibility_id = format!(
                    "transition::{}::{}::feasibility",
                    transition.id, branch.name
                );
                let feasibility_query = SolverQuery {
                    id: feasibility_id.clone(),
                    symbols: symbols.clone(),
                    assertions: branch_context.clone(),
                };
                match self.solve(&feasibility_query, deadline) {
                    Ok(DecisionResult::Sat(counterexample)) => records.push(VerificationRecord {
                        obligation_id: feasibility_id,
                        obligation_kind: "transition_feasibility".to_owned(),
                        outcome: VerificationOutcome::Satisfiable,
                        counterexample: Some(counterexample),
                    }),
                    Ok(DecisionResult::Unsat) => {
                        violated = true;
                        diagnostics.push(
                            Diagnostic::error(
                                transition_code(transition.kind),
                                format!(
                                    "transition `{}` branch `{}` is infeasible under its preserved preconditions",
                                    transition.id, branch.name
                                ),
                            )
                            .for_subject(&transition.id),
                        );
                        records.push(VerificationRecord {
                            obligation_id: feasibility_id,
                            obligation_kind: "transition_feasibility".to_owned(),
                            outcome: VerificationOutcome::Unsatisfiable,
                            counterexample: None,
                        });
                        continue;
                    }
                    Ok(DecisionResult::Unknown(reason)) => {
                        undecided = true;
                        diagnostics.push(solver_diagnostic(&feasibility_id, reason));
                        records.push(VerificationRecord {
                            obligation_id: feasibility_id,
                            obligation_kind: "transition_feasibility".to_owned(),
                            outcome: VerificationOutcome::Indeterminate,
                            counterexample: None,
                        });
                        continue;
                    }
                    Err(error) => {
                        undecided = true;
                        diagnostics.push(solver_diagnostic(&feasibility_id, error.to_string()));
                        records.push(VerificationRecord {
                            obligation_id: feasibility_id,
                            obligation_kind: "transition_feasibility".to_owned(),
                            outcome: VerificationOutcome::Indeterminate,
                            counterexample: None,
                        });
                        continue;
                    }
                }

                for invariant in preserved {
                    let mut assertions = branch_context.clone();
                    assertions.push(negate(invariant.expression.to_post_state()));
                    let query = SolverQuery {
                        id: format!(
                            "transition::{}::{}::preserves::{}",
                            transition.id, branch.name, invariant.id
                        ),
                        symbols: symbols.clone(),
                        assertions,
                    };
                    match self.solve(&query, deadline) {
                        Ok(DecisionResult::Unsat) => records.push(VerificationRecord {
                            obligation_id: query.id,
                            obligation_kind: "transition_preservation".to_owned(),
                            outcome: VerificationOutcome::Unsatisfiable,
                            counterexample: None,
                        }),
                        Ok(DecisionResult::Sat(counterexample)) => {
                            violated = true;
                            diagnostics.push(
                                Diagnostic::error(
                                    transition_code(transition.kind),
                                    format!(
                                        "transition `{}` branch `{}` does not preserve `{}`",
                                        transition.id, branch.name, invariant.id
                                    ),
                                )
                                .for_subject(&transition.id),
                            );
                            records.push(VerificationRecord {
                                obligation_id: query.id,
                                obligation_kind: "transition_preservation".to_owned(),
                                outcome: VerificationOutcome::Satisfiable,
                                counterexample: Some(counterexample),
                            });
                        }
                        Ok(DecisionResult::Unknown(reason)) => {
                            undecided = true;
                            diagnostics.push(solver_diagnostic(&query.id, reason));
                            records.push(VerificationRecord {
                                obligation_id: query.id,
                                obligation_kind: "transition_preservation".to_owned(),
                                outcome: VerificationOutcome::Indeterminate,
                                counterexample: None,
                            });
                        }
                        Err(error) => {
                            undecided = true;
                            diagnostics.push(solver_diagnostic(&query.id, error.to_string()));
                            records.push(VerificationRecord {
                                obligation_id: query.id,
                                obligation_kind: "transition_preservation".to_owned(),
                                outcome: VerificationOutcome::Indeterminate,
                                counterexample: None,
                            });
                        }
                    }
                }
            }
        }

        if violated || undecided {
            return CompileResult {
                status: if violated {
                    CompileStatus::InvariantViolated
                } else {
                    CompileStatus::Indeterminate
                },
                diagnostics,
                verification: records,
                excluded_claims: checked.excluded_claims.clone(),
                artifacts: None,
            };
        }

        match build_artifacts(checked, solver_identity, self.config.signing_key.as_ref()) {
            Ok(artifacts) => CompileResult {
                status: CompileStatus::StaticallyCertified,
                diagnostics,
                verification: records,
                excluded_claims: checked.excluded_claims.clone(),
                artifacts: Some(artifacts),
            },
            Err(error) => CompileResult {
                status: CompileStatus::Indeterminate,
                diagnostics: vec![Diagnostic::error(
                    codes::ARTIFACT_FAILURE,
                    error.to_string(),
                )],
                verification: records,
                excluded_claims: checked.excluded_claims.clone(),
                artifacts: None,
            },
        }
    }

    fn solve(&self, query: &SolverQuery, deadline: Instant) -> Result<DecisionResult, SolverError> {
        let remaining = deadline.saturating_duration_since(Instant::now());
        if remaining.is_zero() {
            return Err(SolverError::Timeout(duration_ms_u64(
                self.config.max_compile_time,
            )));
        }
        let timeout = self.config.solver_timeout.min(remaining);
        self.solver.solve(query, timeout)
    }

    fn source_limit_diagnostic(&self, source: &str) -> Option<Diagnostic> {
        (source.len() > self.config.max_source_bytes).then(|| {
            Diagnostic::error(
                codes::RESOURCE_LIMIT,
                format!(
                    "source contains {} bytes; the configured limit is {}",
                    source.len(),
                    self.config.max_source_bytes
                ),
            )
        })
    }
}

fn solver_obligation_count(checked: &CheckedContract) -> Option<usize> {
    let mut count = 1_usize.checked_add(checked.invariants.len())?;
    for transition in &checked.transitions {
        let per_branch = 1_usize.checked_add(transition.preserves.len())?;
        count = count.checked_add(per_branch.checked_mul(transition.branches.len())?)?;
    }
    Some(count)
}

fn resource_indeterminate(checked: &CheckedContract, message: String) -> CompileResult {
    CompileResult {
        status: CompileStatus::Indeterminate,
        diagnostics: vec![Diagnostic::error(codes::RESOURCE_LIMIT, message)],
        verification: Vec::new(),
        excluded_claims: checked.excluded_claims.clone(),
        artifacts: None,
    }
}

fn duration_ms_u64(duration: Duration) -> u64 {
    u64::try_from(duration.as_millis()).unwrap_or(u64::MAX)
}

fn summary(checked: &CheckedContract) -> CheckSummary {
    CheckSummary {
        contract_id: checked.contract_id.clone(),
        hard_assumptions: checked.assumptions.len(),
        hard_invariants: checked.invariants.len(),
        transitions: checked.transitions.len(),
        linear_tokens: checked.linear_tokens.len(),
        excluded_claims: checked.excluded_claims.len(),
    }
}

fn negate(expression: Expr) -> Expr {
    Expr {
        span: expression.span,
        kind: ExprKind::Unary {
            operator: lambda_safe_model::UnaryOperator::Not,
            expression: Box::new(expression),
        },
    }
}

fn solver_diagnostic(obligation: &str, reason: impl Into<String>) -> Diagnostic {
    Diagnostic::error(
        codes::SOLVER_INDETERMINATE,
        format!(
            "solver could not safely decide obligation `{obligation}`: {}",
            reason.into()
        ),
    )
    .for_subject(obligation)
}

fn indeterminate(
    checked: &CheckedContract,
    mut records: Vec<VerificationRecord>,
    obligation_id: String,
    reason: impl Into<String>,
) -> CompileResult {
    let reason = reason.into();
    records.push(VerificationRecord {
        obligation_id: obligation_id.clone(),
        obligation_kind: "context_feasibility".to_owned(),
        outcome: VerificationOutcome::Indeterminate,
        counterexample: None,
    });
    CompileResult {
        status: CompileStatus::Indeterminate,
        diagnostics: vec![solver_diagnostic(&obligation_id, reason)],
        verification: records,
        excluded_claims: checked.excluded_claims.clone(),
        artifacts: None,
    }
}

const fn transition_code(kind: lambda_safe_model::TransitionKind) -> &'static str {
    match kind {
        lambda_safe_model::TransitionKind::Degrade => codes::DEGRADE_VIOLATION,
        lambda_safe_model::TransitionKind::Reconcile => codes::RECONCILE_VIOLATION,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use lambda_safe_solver::FiniteModelSolver;

    fn compiler() -> Compiler {
        Compiler::new(
            Arc::new(FiniteModelSolver::default()),
            CompilerConfig::default(),
        )
    }

    fn valid_source(metadata: &str) -> String {
        format!(
            r#"lambda_safe "0.1";
contract capacity version "1.0.0" {{
  unit cpu;
  const zero: int<cpu> = 0;
  input allocated: int<cpu> authority control_plane range [0, 3];
  input capacity: int<cpu> authority control_plane range [0, 3];
  assume admissible hard: allocated <= capacity;
  invariant within_capacity hard: allocated <= capacity;
  invariant prediction soft: allocated <= capacity;
  metadata note = "{metadata}";
}}"#
        )
    }

    #[test]
    fn certifies_valid_bounded_contract() {
        let result = compiler().compile(&valid_source("one"), SourceFormat::Lambda);
        assert_eq!(result.status, CompileStatus::StaticallyCertified);
        assert!(result.artifacts.is_some());
    }

    #[test]
    fn soft_metadata_does_not_change_certificate() {
        let first = compiler().compile(&valid_source("one"), SourceFormat::Lambda);
        let second = compiler().compile(&valid_source("two"), SourceFormat::Lambda);
        let first_digest = first
            .artifacts
            .expect("first compile should certify")
            .certificate
            .certificate_digest;
        let second_digest = second
            .artifacts
            .expect("second compile should certify")
            .certificate
            .certificate_digest;
        assert_eq!(first_digest, second_digest);
    }

    #[test]
    fn rejects_counterexample() {
        let source = r#"lambda_safe "0.1";
contract capacity version "1.0.0" {
  unit cpu;
  input allocated: int<cpu> authority control_plane range [0, 2];
  input capacity: int<cpu> authority control_plane range [0, 2];
  invariant within_capacity hard: allocated <= capacity;
}"#;
        let result = compiler().compile(source, SourceFormat::Lambda);
        assert_eq!(result.status, CompileStatus::InvariantViolated);
        assert!(result.artifacts.is_none());
    }

    #[test]
    fn rejects_infeasible_context() {
        let source = r#"lambda_safe "0.1";
contract impossible version "1.0.0" {
  unit count;
  const zero: int<count> = 0;
  input x: int<count> authority control_plane range [0, 2];
  assume impossible hard: x < zero;
  invariant harmless hard: x >= zero;
}"#;
        let result = compiler().compile(source, SourceFormat::Lambda);
        assert_eq!(result.status, CompileStatus::InfeasibleContext);
        assert!(result.artifacts.is_none());
    }

    #[test]
    fn verifies_emitted_pair() {
        let compiler = compiler();
        let artifacts = compiler
            .compile(&valid_source("verify"), SourceFormat::Lambda)
            .artifacts
            .expect("compile should certify");
        assert!(
            compiler
                .verify(&artifacts.manifest, &artifacts.certificate)
                .valid
        );
    }
}
